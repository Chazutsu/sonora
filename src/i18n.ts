export type SonoraCopy = { [Key in keyof typeof messages.en]: string };

export function resolveLocale(
	preference: SonoraSettings["interfaceLanguage"],
	systemLanguage = navigator.language,
): "en" | "ja" {
	if (preference !== "system") return preference;
	return systemLanguage.toLowerCase().startsWith("ja") ? "ja" : "en";
}

export function copyFor(
	preference: SonoraSettings["interfaceLanguage"],
	systemLanguage?: string,
): SonoraCopy {
	return messages[resolveLocale(preference, systemLanguage)];
}

export function recordingSaveMessages(copy: SonoraCopy, limit: "duration" | "size" | null) {
	return {
		saved:
			limit === "duration"
				? copy.recordingSavedAfterDurationLimit
				: limit === "size"
					? copy.recordingSavedAfterSizeLimit
					: copy.recordingSaved,
		failed: copy.recordingFailed,
		audioSaved: (path: string) => copy.recordingLinkFailed.replace("{path}", path),
	};
}
